#!/usr/bin/env bash
# Build the gh-pages site: every reports/<slug>/ copied as is, plus an index.html listing them
# (kind, period, who, sessions, projects — read from each report.yaml) newest first.
# Usage: scripts/build-site.sh <out-dir>   (bash + coreutils only)
set -euo pipefail
out=${1:?out dir}
root=$(cd "$(dirname "$0")/.." && pwd)
rm -rf "$out" && mkdir -p "$out" && touch "$out/.nojekyll"

field() { sed -n "s/^$2: *//p" "$1" | head -1; }
esc() { sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }

rows=""
for dir in $(ls -d "$root"/reports/*/ | sort -r); do
  slug=$(basename "$dir")
  [ -f "$dir/report.yaml" ] || continue
  cp -r "$dir" "$out/$slug"
  kind=$(field "$dir/report.yaml" kind); label=$(field "$dir/report.yaml" label | esc)
  who=$(field "$dir/report.yaml" who | esc); start=$(field "$dir/report.yaml" start | cut -c1-10)
  end=$(field "$dir/report.yaml" end | cut -c1-10); gen=$(field "$dir/report.yaml" generated | cut -c1-16 | tr T ' ')
  sessions=$(field "$dir/report.yaml" sessions); projects=$(field "$dir/report.yaml" projects)
  yaml=""
  for t in report project_totals working_by_day sessions session_days; do
    [ -f "$dir/$t.yaml" ] && yaml="$yaml<a href=\"$slug/$t.yaml\">$t</a> "
  done
  rows="$rows<tr><td class=k>$kind</td><td><a href=\"$slug/report.html\"><b>$label</b></a></td><td>$start → $end</td><td>$who</td><td class=n>$sessions</td><td class=n>$projects</td><td><a href=\"$slug/report.html\">html</a> <a href=\"$slug/report.md\">md</a></td><td class=y>$yaml</td><td class=g>$gen</td></tr>
"
done

cat > "$out/index.html" <<HTML
<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Devin session reports</title>
<meta name="viewport" content="width=device-width,initial-scale=1">
<style>
body{font:15px/1.45 system-ui,sans-serif;margin:2rem auto;max-width:72rem;padding:0 1rem;color:#1b1f24}
h1{font-size:1.5rem;margin:0 0 .25rem} p{color:#57606a;margin:0 0 1.25rem}
table{border-collapse:collapse;width:100%} th,td{text-align:left;padding:.45rem .6rem;border-bottom:1px solid #d0d7de;vertical-align:top}
th{font-weight:600;color:#57606a;font-size:.85rem;text-transform:uppercase;letter-spacing:.03em}
td.k{text-transform:capitalize} td.n{text-align:right;font-variant-numeric:tabular-nums} td.y a{margin-right:.4rem;font-size:.9rem} td.g{color:#57606a;white-space:nowrap;font-size:.9rem}
a{color:#0969da;text-decoration:none} a:hover{text-decoration:underline}
</style></head><body>
<h1>Devin session reports</h1>
<p>Daily, weekly and monthly reports by project → session, generated by <a href="https://github.com/${GITHUB_REPOSITORY:-Open-MBEE/devin-automation}">session-report</a>. Newest first; the YAML tables are the data behind each report.</p>
<table><thead><tr><th>Kind</th><th>Report</th><th>Period</th><th>For</th><th>Sessions</th><th>Projects</th><th>Formats</th><th>YAML tables</th><th>Generated</th></tr></thead>
<tbody>
$rows</tbody></table>
</body></html>
HTML
echo "site: $out ($(ls -d "$out"/*/ | wc -l) reports)"
